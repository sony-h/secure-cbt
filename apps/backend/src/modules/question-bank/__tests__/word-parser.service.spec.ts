import { describe, it, expect, vi } from 'vitest';
import { WordParserService } from '../parsers/word-parser.service';
import { QuestionType, DifficultyLevel } from '@secure-cbt/shared';
import * as mammoth from 'mammoth';

vi.mock('mammoth', () => ({
  convertToHtml: vi.fn(),
  images: {
    imgElement: vi.fn((fn) => fn),
  },
}));

describe('WordParserService', () => {
  const service = new WordParserService();

  it('should parse questions from HTML tables generated by mammoth', async () => {
    const mockHtml = `
      <table>
        <tr><td>1.</td><td>Ibu kota negara Indonesia yang baru bernama...</td></tr>
        <tr><td>A</td><td>Bandung</td></tr>
        <tr><td>B</td><td>Surabaya</td></tr>
        <tr><td>C</td><td>Nusantara</td></tr>
        <tr><td>D</td><td>Medan</td></tr>
        <tr><td>E</td><td>Makassar</td></tr>
        <tr><td>KUNCI</td><td>C</td></tr>
        <tr><td>PEMBAHASAN</td><td>IKN bernama Nusantara berlokasi di Kaltim.</td></tr>
      </table>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    const q1 = result[0];
    expect(q1.content).toBe('Ibu kota negara Indonesia yang baru bernama...');
    expect(q1.type).toBe(QuestionType.MULTIPLE_CHOICE);
    expect(q1.options).toHaveLength(5);
    expect(q1.options[0].content).toBe('Bandung');
    expect(q1.options[0].is_correct).toBe(false);
    expect(q1.options[2].content).toBe('Nusantara');
    expect(q1.options[2].is_correct).toBe(true);
    expect(q1.explanation).toBe('IKN bernama Nusantara berlokasi di Kaltim.');
    expect(q1.valid).toBe(true);
    expect(q1.error).toBeNull();
  });

  it('should mark question invalid if key is missing or not in options', async () => {
    const mockHtml = `
      <table>
        <tr><td>1.</td><td>Berapa hasil dari 2 + 2?</td></tr>
        <tr><td>A</td><td>3</td></tr>
        <tr><td>B</td><td>4</td></tr>
        <tr><td>KUNCI</td><td>Z</td></tr>
      </table>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].valid).toBe(false);
    expect(result[0].error).toContain("Kunci jawaban 'Z' tidak ditemukan");
  });

  it('should parse paragraph blocks if no tables are found', async () => {
    const mockHtml = `
      <p>1. Bahasa resmi di Indonesia adalah?</p>
      <p>A. Bahasa Jawa</p>
      <p>B. Bahasa Indonesia</p>
      <p>C. Bahasa Sunda</p>
      <p>KUNCI: B</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toBe('Bahasa resmi di Indonesia adalah?');
    expect(result[0].options).toHaveLength(3);
    expect(result[0].options[1].content).toBe('Bahasa Indonesia');
    expect(result[0].options[1].is_correct).toBe(true);
    expect(result[0].valid).toBe(true);
  });

  it('should parse natural format with [SOAL N], multi-paragraph stimulus, and embedded image', async () => {
    const mockHtml = `
      <p>[SOAL 1]</p>
      <p>Perhatikan gambar diagram siklus air di bawah ini:</p>
      <p><img src="https://storage.example.com/questions/water-cycle.webp" /></p>
      <p>Tahapan yang ditunjukkan oleh nomor 3 adalah proses pengembunan uap air menjadi awan. Nama proses tersebut adalah...</p>
      <p>A. Evaporasi</p>
      <p>B. Kondensasi</p>
      <p>C. Presipitasi</p>
      <p>D. Transpirasi</p>
      <p>E. Infiltrasi</p>
      <p>KUNCI: B</p>
      <p>PEMBAHASAN: Kondensasi adalah proses perubahan wujud gas menjadi cair membentuk awan.</p>
      <p>KESULITAN: SULIT</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    const q = result[0];
    expect(q.content).toContain('Perhatikan gambar diagram');
    expect(q.content).toContain('Tahapan yang ditunjukkan oleh nomor 3');
    expect(q.image_url).toBe('https://storage.example.com/questions/water-cycle.webp');
    expect(q.options).toHaveLength(5);
    expect(q.options[1].content).toBe('Kondensasi');
    expect(q.options[1].is_correct).toBe(true);
    expect(q.difficulty).toBe(DifficultyLevel.HARD);
    expect(q.explanation).toContain('Kondensasi adalah proses');
    expect(q.valid).toBe(true);
  });

  it('should use natural format even if decorative or instruction table exists', async () => {
    const mockHtml = `
      <table>
        <tr><td>Petunjuk Umum:</td><td>Kerjakan soal dengan teliti dan jujur.</td></tr>
      </table>
      <p>[SOAL 1]</p>
      <p>Siapakah presiden pertama Indonesia?</p>
      <p>A. Soeharto</p>
      <p>B. Ir. Soekarno</p>
      <p>KUNCI: B</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toContain('Siapakah presiden pertama Indonesia?');
    expect(result[0].options).toHaveLength(2);
    expect(result[0].options[1].is_correct).toBe(true);
    expect(result[0].valid).toBe(true);
  });
});

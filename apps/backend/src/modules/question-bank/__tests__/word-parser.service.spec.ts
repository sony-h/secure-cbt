import { describe, it, expect, vi } from 'vitest';
import { WordParserService } from '../parsers/word-parser.service';
import { QuestionType, DifficultyLevel } from '@secure-cbt/shared';
import * as mammoth from 'mammoth';

vi.mock('mammoth', () => ({
  convertToHtml: vi.fn(),
  images: {
    imgElement: vi.fn((fn) => fn),
  },
}));

describe('WordParserService', () => {
  const service = new WordParserService();

  it('should parse questions from HTML tables generated by mammoth', async () => {
    const mockHtml = `
      <table>
        <tr><td>1.</td><td>Ibu kota negara Indonesia yang baru bernama...</td></tr>
        <tr><td>A</td><td>Bandung</td></tr>
        <tr><td>B</td><td>Surabaya</td></tr>
        <tr><td>C</td><td>Nusantara</td></tr>
        <tr><td>D</td><td>Medan</td></tr>
        <tr><td>E</td><td>Makassar</td></tr>
        <tr><td>KUNCI</td><td>C</td></tr>
        <tr><td>PEMBAHASAN</td><td>IKN bernama Nusantara berlokasi di Kaltim.</td></tr>
      </table>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    const q1 = result[0];
    expect(q1.content).toBe('Ibu kota negara Indonesia yang baru bernama...');
    expect(q1.type).toBe(QuestionType.MULTIPLE_CHOICE);
    expect(q1.options).toHaveLength(5);
    expect(q1.options[0].content).toBe('Bandung');
    expect(q1.options[0].is_correct).toBe(false);
    expect(q1.options[2].content).toBe('Nusantara');
    expect(q1.options[2].is_correct).toBe(true);
    expect(q1.explanation).toBe('IKN bernama Nusantara berlokasi di Kaltim.');
    expect(q1.valid).toBe(true);
    expect(q1.error).toBeNull();
  });

  it('should mark question invalid if key is missing or not in options', async () => {
    const mockHtml = `
      <table>
        <tr><td>1.</td><td>Berapa hasil dari 2 + 2?</td></tr>
        <tr><td>A</td><td>3</td></tr>
        <tr><td>B</td><td>4</td></tr>
        <tr><td>KUNCI</td><td>Z</td></tr>
      </table>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].valid).toBe(false);
    expect(result[0].error).toContain("Kunci jawaban 'Z' tidak ditemukan");
  });

  it('should parse paragraph blocks if no tables are found', async () => {
    const mockHtml = `
      <p>1. Bahasa resmi di Indonesia adalah?</p>
      <p>A. Bahasa Jawa</p>
      <p>B. Bahasa Indonesia</p>
      <p>C. Bahasa Sunda</p>
      <p>KUNCI: B</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toBe('Bahasa resmi di Indonesia adalah?');
    expect(result[0].options).toHaveLength(3);
    expect(result[0].options[1].content).toBe('Bahasa Indonesia');
    expect(result[0].options[1].is_correct).toBe(true);
    expect(result[0].valid).toBe(true);
  });

  it('should parse natural format with [SOAL N], multi-paragraph stimulus, and embedded image', async () => {
    const mockHtml = `
      <p>[SOAL 1]</p>
      <p>Perhatikan gambar diagram siklus air di bawah ini:</p>
      <p><img src="https://storage.example.com/questions/water-cycle.webp" /></p>
      <p>Tahapan yang ditunjukkan oleh nomor 3 adalah proses pengembunan uap air menjadi awan. Nama proses tersebut adalah...</p>
      <p>A. Evaporasi</p>
      <p>B. Kondensasi</p>
      <p>C. Presipitasi</p>
      <p>D. Transpirasi</p>
      <p>E. Infiltrasi</p>
      <p>KUNCI: B</p>
      <p>PEMBAHASAN: Kondensasi adalah proses perubahan wujud gas menjadi cair membentuk awan.</p>
      <p>KESULITAN: SULIT</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    const q = result[0];
    expect(q.content).toContain('Perhatikan gambar diagram');
    expect(q.content).toContain('Tahapan yang ditunjukkan oleh nomor 3');
    expect(q.image_url).toBe('https://storage.example.com/questions/water-cycle.webp');
    expect(q.options).toHaveLength(5);
    expect(q.options[1].content).toBe('Kondensasi');
    expect(q.options[1].is_correct).toBe(true);
    expect(q.difficulty).toBe(DifficultyLevel.HARD);
    expect(q.explanation).toContain('Kondensasi adalah proses');
    expect(q.valid).toBe(true);
  });

  it('should use natural format even if decorative or instruction table exists', async () => {
    const mockHtml = `
      <table>
        <tr><td>Petunjuk Umum:</td><td>Kerjakan soal dengan teliti dan jujur.</td></tr>
      </table>
      <p>[SOAL 1]</p>
      <p>Siapakah presiden pertama Indonesia?</p>
      <p>A. Soeharto</p>
      <p>B. Ir. Soekarno</p>
      <p>KUNCI: B</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toContain('Siapakah presiden pertama Indonesia?');
    expect(result[0].options).toHaveLength(2);
    expect(result[0].options[1].is_correct).toBe(true);
    expect(result[0].valid).toBe(true);
  });

  it('should cleanly strip colon in "A : Pilihan" and not treat English sentences as options (C-2)', async () => {
    const mockHtml = `
      <p>[SOAL 1]</p>
      <p>Read the following text carefully:</p>
      <p>A student conducted a chemical reaction in the laboratory yesterday.</p>
      <p>What did the student do?</p>
      <p>A : Conducted a chemical reaction</p>
      <p>B : Slept in the classroom</p>
      <p>KUNCI: A</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toContain('A student conducted a chemical reaction');
    expect(result[0].options).toHaveLength(2);
    expect(result[0].options[0].content).toBe('Conducted a chemical reaction');
    expect(result[0].options[0].content).not.toContain(':');
    expect(result[0].options[0].is_correct).toBe(true);
  });

  it('should keep multi-paragraph PEMBAHASAN within explanation instead of polluting last option (C-3)', async () => {
    const mockHtml = `
      <p>[SOAL 1]</p>
      <p>Apakah ibu kota Indonesia?</p>
      <p>A. Jakarta</p>
      <p>B. Nusantara</p>
      <p>KUNCI: B</p>
      <p>PEMBAHASAN: Paragraf pertama penjelasan tentang Nusantara.</p>
      <p>Paragraf kedua penjelasan mengenai lokasi di Kalimantan Timur.</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].options[1].content).toBe('Nusantara');
    expect(result[0].options[1].content).not.toContain('Paragraf kedua');
    expect(result[0].explanation).toContain('Paragraf pertama');
    expect(result[0].explanation).toContain('Paragraf kedua penjelasan mengenai lokasi');
  });

  it('should ignore administrative table with KUNCI but zero options and fallback to paragraphs (I-3)', async () => {
    const mockHtml = `
      <table>
        <tr><td>KUNCI</td><td>Disimpan oleh pengawas ruangan ujian</td></tr>
      </table>
      <p>[SOAL 1]</p>
      <p>2 + 2 = ?</p>
      <p>A. 3</p>
      <p>B. 4</p>
      <p>KUNCI: B</p>
    `;

    vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
      value: mockHtml,
      messages: [],
    });

    const result = await service.parse(Buffer.from('fake-docx-data'));

    expect(result).toHaveLength(1);
    expect(result[0].content).toBe('2 + 2 = ?');
    expect(result[0].options).toHaveLength(2);
    expect(result[0].options[1].is_correct).toBe(true);
  });

  describe('Multi-Type Questions Parsing', () => {
    it('should parse MULTI_SELECT question with TIPE: PG_KOMPLEKS and comma-separated keys', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: PG_KOMPLEKS</p>
        <p>Manakah yang merupakan bahasa pemrograman interpreted?</p>
        <p>A. Python</p>
        <p>B. JavaScript</p>
        <p>C. C++</p>
        <p>D. Ruby</p>
        <p>KUNCI: A, B, D</p>
        <p>PEMBAHASAN: Python, JS, dan Ruby diinterpretasi saat runtime.</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      const q = result[0];
      expect(q.type).toBe(QuestionType.MULTI_SELECT);
      expect(q.options).toHaveLength(4);
      expect(q.options[0].is_correct).toBe(true); // A
      expect(q.options[1].is_correct).toBe(true); // B
      expect(q.options[2].is_correct).toBe(false); // C
      expect(q.options[3].is_correct).toBe(true); // D
      expect(q.valid).toBe(true);
    });

    it('should parse TRUE_FALSE question with TIPE: BENAR_SALAH and synthesize Benar/Salah options', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: BENAR_SALAH</p>
        <p>Fotosintesis menghasilkan oksigen dan glukosa.</p>
        <p>KUNCI: BENAR</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      const q = result[0];
      expect(q.type).toBe(QuestionType.TRUE_FALSE);
      expect(q.options).toHaveLength(2);
      expect(q.options[0].content).toBe('Benar');
      expect(q.options[0].is_correct).toBe(true);
      expect(q.options[1].content).toBe('Salah');
      expect(q.options[1].is_correct).toBe(false);
      expect(q.valid).toBe(true);
    });

    it('should parse SHORT_ANSWER question with TIPE: ISIAN_SINGKAT and convert key into options', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: ISIAN_SINGKAT</p>
        <p>Bahasa resmi Brazil adalah...</p>
        <p>KUNCI: Portugis, Portuguese</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      const q = result[0];
      expect(q.type).toBe(QuestionType.SHORT_ANSWER);
      expect(q.options.length).toBeGreaterThanOrEqual(1);
      expect(q.options[0].content).toBe('Portugis');
      expect(q.options[0].is_correct).toBe(true);
      expect(q.valid).toBe(true);
    });

    it('should parse MATCHING question with TIPE: MENJODOHKAN and arrow notation', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: MENJODOHKAN</p>
        <p>Jodohkanlah pahlawan nasional dengan asalnya:</p>
        <p>A. R.A. Kartini -> Jepara</p>
        <p>B. Cut Nyak Dien -> Aceh</p>
        <p>C. Pangeran Diponegoro -> Yogyakarta</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      const q = result[0];
      expect(q.type).toBe(QuestionType.MATCHING);
      expect(q.options).toHaveLength(3);
      const opt1 = JSON.parse(q.options[0].content);
      expect(opt1.left).toBe('R.A. Kartini');
      expect(opt1.right).toBe('Jepara');
      expect(q.options[0].is_correct).toBe(true);
      expect(q.valid).toBe(true);
    });

    it('should parse ESSAY question with TIPE: ESAI, no options and no key', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: ESAI</p>
        <p>Jelaskan proses siklus Krebs dalam respirasi aerobik!</p>
        <p>PEMBAHASAN: Siklus Krebs terjadi di matriks mitokondria.</p>
        <p>[SOAL 2]</p>
        <p>A. 1</p>
        <p>B. 2</p>
        <p>KUNCI: A</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(2);
      const essay = result[0];
      expect(essay.type).toBe(QuestionType.ESSAY);
      expect(essay.content).toContain('Jelaskan proses siklus Krebs');
      expect(essay.options).toHaveLength(0);
      expect(essay.explanation).toContain('Siklus Krebs terjadi');
      expect(essay.valid).toBe(true);

      const mcq = result[1];
      expect(mcq.type).toBe(QuestionType.MULTIPLE_CHOICE);
      expect(mcq.options).toHaveLength(2);
    });

    it('should auto-detect MULTI_SELECT when key contains multiple letters without TIPE tag', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>Pilihlah bilangan prima di bawah ini:</p>
        <p>A. 2</p>
        <p>B. 3</p>
        <p>C. 4</p>
        <p>D. 5</p>
        <p>KUNCI: A, B, D</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.MULTI_SELECT);
      expect(result[0].options[0].is_correct).toBe(true);
      expect(result[0].options[1].is_correct).toBe(true);
      expect(result[0].options[2].is_correct).toBe(false);
      expect(result[0].options[3].is_correct).toBe(true);
    });

    it('should auto-detect TRUE_FALSE when key is BENAR or SALAH', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>Bulan memancarkan cahayanya sendiri.</p>
        <p>KUNCI: SALAH</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.TRUE_FALSE);
      expect(result[0].options).toHaveLength(2);
      expect(result[0].options[1].content).toBe('Salah');
      expect(result[0].options[1].is_correct).toBe(true);
    });

    it('should auto-detect MATCHING when options contain arrow syntax ->', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>Pasangkan ibukota negara berikut:</p>
        <p>A. Indonesia -> Jakarta</p>
        <p>B. Jepang -> Tokyo</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.MATCHING);
      expect(result[0].options).toHaveLength(2);
    });

    it('should correctly normalize "TIPE: PILIHAN GANDA KOMPLEKS" to MULTI_SELECT', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: PILIHAN GANDA KOMPLEKS</p>
        <p>Pilihlah bahasa yang berjalan di browser:</p>
        <p>A. JavaScript</p>
        <p>B. WebAssembly</p>
        <p>C. Python</p>
        <p>KUNCI: A, B</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.MULTI_SELECT);
      expect(result[0].options[0].is_correct).toBe(true);
      expect(result[0].options[1].is_correct).toBe(true);
      expect(result[0].options[2].is_correct).toBe(false);
    });

    it('should parse TRUE_FALSE with explicit A: Benar, B: Salah and key B without marking both correct', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: BENAR_SALAH</p>
        <p>Bumi itu datar.</p>
        <p>A. Benar</p>
        <p>B. Salah</p>
        <p>KUNCI: B</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.TRUE_FALSE);
      expect(result[0].options[0].is_correct).toBe(false);
      expect(result[0].options[1].is_correct).toBe(true);
    });

    it('should parse TRUE_FALSE with explicit A: Benar, B: Salah and key SALAH correctly', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>TIPE: BENAR_SALAH</p>
        <p>Bumi itu datar.</p>
        <p>A. Benar</p>
        <p>B. Salah</p>
        <p>KUNCI: SALAH</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.TRUE_FALSE);
      expect(result[0].options[0].is_correct).toBe(false);
      expect(result[0].options[1].is_correct).toBe(true);
    });

    it('should auto-detect MATCHING when options contain unicode arrow →', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>Pasangkan rumus kimia dan senyawa:</p>
        <p>A. H2O → Air</p>
        <p>B. NaCl → Garam Dapur</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.MATCHING);
      expect(result[0].options).toHaveLength(2);
      const parsed1 = JSON.parse(result[0].options[0].content);
      expect(parsed1.left).toBe('H2O');
      expect(parsed1.right).toBe('Air');
    });

    it('should auto-detect ESSAY when options and key are both omitted without TIPE tag', async () => {
      const mockHtml = `
        <p>[SOAL 1]</p>
        <p>Jelaskan secara mendalam proses pembentukan batuan sedimen!</p>
      `;

      vi.mocked(mammoth.convertToHtml).mockResolvedValueOnce({
        value: mockHtml,
        messages: [],
      });

      const result = await service.parse(Buffer.from('fake-docx-data'));

      expect(result).toHaveLength(1);
      expect(result[0].type).toBe(QuestionType.ESSAY);
      expect(result[0].options).toHaveLength(0);
      expect(result[0].valid).toBe(true);
    });
  });
});

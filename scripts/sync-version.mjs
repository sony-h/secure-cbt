#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

const SEMVER_REGEX = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-((?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*)(?:\.(?:0|[1-9]\d*|\d*[a-zA-Z-][0-9a-zA-Z-]*))*))?(?:\+([0-9a-zA-Z-]+(?:\.[0-9a-zA-Z-]+)*))?$/;

/**
 * Parse a SemVer string into components.
 * @param {string} str
 */
export function parseVersion(str) {
  if (typeof str !== 'string') {
    throw new Error('Version must be a string');
  }
  const match = str.trim().match(SEMVER_REGEX);
  if (!match) {
    throw new Error(`Invalid SemVer version string: "${str}". Expected format: MAJOR.MINOR.PATCH (e.g. 1.9.0)`);
  }
  const major = parseInt(match[1], 10);
  const minor = parseInt(match[2], 10);
  const patch = parseInt(match[3], 10);
  const prerelease = match[4];
  const buildStr = match[5];
  const buildNumber = buildStr && /^\d+$/.test(buildStr) ? parseInt(buildStr, 10) : undefined;

  return { major, minor, patch, prerelease, buildNumber };
}

/**
 * Compute the next version and build number.
 * @param {string} currentVersion
 * @param {number} currentBuildNumber
 * @param {'patch'|'minor'|'major'|string} bumpType
 * @param {number} [specifiedBuildNumber]
 */
export function computeNextVersion(currentVersion, currentBuildNumber, bumpType, specifiedBuildNumber) {
  const current = parseVersion(currentVersion);
  let nextVersion;
  const nextBuild = specifiedBuildNumber !== undefined ? Number(specifiedBuildNumber) : (currentBuildNumber || 1) + 1;

  if (bumpType === 'patch') {
    nextVersion = `${current.major}.${current.minor}.${current.patch + 1}`;
  } else if (bumpType === 'minor') {
    nextVersion = `${current.major}.${current.minor + 1}.0`;
  } else if (bumpType === 'major') {
    nextVersion = `${current.major + 1}.0.0`;
  } else {
    // Explicit SemVer version string passed
    const parsed = parseVersion(bumpType);
    nextVersion = `${parsed.major}.${parsed.minor}.${parsed.patch}${parsed.prerelease ? `-${parsed.prerelease}` : ''}`;
    if (parsed.buildNumber !== undefined && specifiedBuildNumber === undefined) {
      return { version: nextVersion, buildNumber: parsed.buildNumber };
    }
  }

  return { version: nextVersion, buildNumber: nextBuild };
}

/**
 * Verify and update file content with the target version and build number.
 * @param {string} fileNameOrType
 * @param {string} content
 * @param {{ version: string, buildNumber: number }} target
 * @returns {string}
 */
export function verifyFileContent(fileNameOrType, content, { version, buildNumber }) {
  const versionString = `${version}+${buildNumber}`;

  if (fileNameOrType.endsWith('package.json')) {
    const json = JSON.parse(content);
    json.version = version;
    return JSON.stringify(json, null, 2) + '\n';
  }

  if (fileNameOrType.endsWith('pubspec.yaml')) {
    return content.replace(/^version:\s*[\d.]+(?:\+\d+)?/m, `version: ${versionString}`);
  }

  if (fileNameOrType.endsWith('app_info.dart')) {
    let result = content;
    result = result.replace(
      /(static\s+const\s+String\s+version\s*=\s*')[^']*(';)/,
      `$1${version}$2`
    );
    result = result.replace(
      /(static\s+const\s+int\s+buildNumber\s*=\s*)\d+(;)/,
      `$1${buildNumber}$2`
    );
    result = result.replace(
      /(static\s+const\s+String\s+versionString\s*=\s*')[^']*(';)/,
      `$1${versionString}$2`
    );
    return result;
  }

  if (fileNameOrType.endsWith('version.ts')) {
    return `// Generated by scripts/sync-version.mjs - DO NOT EDIT MANUALLY
export const APP_VERSION = '${version}';
export const APP_BUILD_NUMBER = ${buildNumber};
export const APP_VERSION_STRING = '${versionString}';
`;
  }

  return content;
}

/**
 * List of all managed files relative to project root.
 */
export const TARGET_FILES = [
  { relativePath: 'package.json', type: 'package.json' },
  { relativePath: 'packages/shared/package.json', type: 'package.json' },
  { relativePath: 'apps/backend/package.json', type: 'package.json' },
  { relativePath: 'apps/dashboard/package.json', type: 'package.json' },
  { relativePath: 'apps/mobile/pubspec.yaml', type: 'pubspec.yaml' },
  { relativePath: 'apps/mobile/lib/core/constants/app_info.dart', type: 'app_info.dart' },
  { relativePath: 'packages/shared/src/constants/version.ts', type: 'version.ts' },
];

/**
 * Check if all target files match the version in version.json.
 * @param {string} rootPath
 * @param {{ version: string, buildNumber: number }} versionData
 */
export function checkTargets(rootPath, versionData) {
  const errors = [];

  for (const target of TARGET_FILES) {
    const fullPath = path.resolve(rootPath, target.relativePath);
    if (!fs.existsSync(fullPath)) {
      errors.push(`Missing file: ${target.relativePath}`);
      continue;
    }

    const content = fs.readFileSync(fullPath, 'utf8');
    const expected = verifyFileContent(target.type, content, versionData);

    if (content !== expected) {
      errors.push(`Out of sync: ${target.relativePath} does not match ${versionData.version} (build: ${versionData.buildNumber})`);
    }
  }

  return {
    inSync: errors.length === 0,
    errors,
  };
}

/**
 * Synchronize all target files with the version in version.json.
 * @param {string} rootPath
 * @param {{ version: string, buildNumber: number, releaseDate?: string }} versionData
 * @param {{ dryRun?: boolean }} options
 */
export function syncTargets(rootPath, versionData, { dryRun = false } = {}) {
  const updatedFiles = [];

  // 1. Sync version.json itself
  const versionJsonPath = path.resolve(rootPath, 'version.json');
  const canonicalJson = JSON.stringify(
    {
      version: versionData.version,
      buildNumber: versionData.buildNumber,
      releaseDate: versionData.releaseDate || new Date().toISOString().split('T')[0],
    },
    null,
    2
  ) + '\n';

  if (!dryRun) {
    fs.writeFileSync(versionJsonPath, canonicalJson, 'utf8');
  }
  updatedFiles.push('version.json');

  // 2. Sync all targets
  for (const target of TARGET_FILES) {
    const fullPath = path.resolve(rootPath, target.relativePath);
    let originalContent = '';

    if (fs.existsSync(fullPath)) {
      originalContent = fs.readFileSync(fullPath, 'utf8');
    } else if (target.type === 'version.ts') {
      originalContent = '';
    } else {
      throw new Error(`Cannot sync target file because it does not exist: ${target.relativePath}`);
    }

    const updatedContent = verifyFileContent(target.type, originalContent, versionData);

    if (originalContent !== updatedContent) {
      if (!dryRun) {
        fs.mkdirSync(path.dirname(fullPath), { recursive: true });
        fs.writeFileSync(fullPath, updatedContent, 'utf8');
      }
      updatedFiles.push(target.relativePath);
    }
  }

  return { updatedFiles };
}

// CLI Execution entrypoint
const isDirectExecution = process.argv[1] && (
  process.argv[1] === __filename ||
  process.argv[1].endsWith('sync-version.mjs')
);

if (isDirectExecution) {
  const versionJsonPath = path.resolve(ROOT_DIR, 'version.json');
  if (!fs.existsSync(versionJsonPath)) {
    console.error('Error: version.json not found in root directory.');
    process.exit(1);
  }

  const raw = fs.readFileSync(versionJsonPath, 'utf8');
  let currentConfig;
  try {
    currentConfig = JSON.parse(raw);
  } catch (err) {
    console.error('Error parsing version.json:', err.message);
    process.exit(1);
  }

  const args = process.argv.slice(2);
  const command = args[0] || 'sync';

  if (command === '--check' || command === 'check') {
    console.log(`Checking version synchronization against version.json (v${currentConfig.version}+${currentConfig.buildNumber})...`);
    const result = checkTargets(ROOT_DIR, currentConfig);
    if (!result.inSync) {
      console.error('\n❌ Version check failed! The following files are out of sync:');
      result.errors.forEach((err) => console.error(`  - ${err}`));
      console.error('\nRun "pnpm version:sync" to synchronize all files.');
      process.exit(1);
    }
    console.log('✅ All target files are in sync with version.json.');
    process.exit(0);
  }

  if (command === 'sync') {
    console.log(`Synchronizing all manifests to v${currentConfig.version}+${currentConfig.buildNumber}...`);
    const { updatedFiles } = syncTargets(ROOT_DIR, currentConfig);
    console.log(`✅ Synchronization complete. Checked/updated ${updatedFiles.length} files.`);
    process.exit(0);
  }

  if (command === 'bump' || ['patch', 'minor', 'major'].includes(command) || /^\d+\.\d+\.\d+/.test(command)) {
    const bumpType = command === 'bump' ? (args[1] || 'patch') : command;
    const customBuild = command === 'bump' ? args[2] : args[1];

    try {
      const next = computeNextVersion(
        currentConfig.version,
        currentConfig.buildNumber,
        bumpType,
        customBuild ? parseInt(customBuild, 10) : undefined
      );

      console.log(`Bumping version from v${currentConfig.version}+${currentConfig.buildNumber} -> v${next.version}+${next.buildNumber}...`);
      const { updatedFiles } = syncTargets(ROOT_DIR, {
        version: next.version,
        buildNumber: next.buildNumber,
        releaseDate: new Date().toISOString().split('T')[0],
      });

      console.log(`✅ Successfully bumped to v${next.version}+${next.buildNumber}!`);
      console.log('Updated files:');
      updatedFiles.forEach((f) => console.log(`  - ${f}`));
      console.log('\nNext steps:');
      console.log('  1. Update apps/dashboard/src/lib/constants/changelog.ts with release highlights');
      console.log('  2. Run pnpm version:check to verify sync');
      console.log('  3. Run pnpm test to verify all suites');
      process.exit(0);
    } catch (err) {
      console.error(`\n❌ Version bump failed: ${err.message}`);
      process.exit(1);
    }
  }

  console.log(`
Usage:
  node scripts/sync-version.mjs sync                     # Sync all files to version.json
  node scripts/sync-version.mjs --check                  # Check if all files match version.json
  node scripts/sync-version.mjs bump <patch|minor|major> # Bump semver and increment build number
  node scripts/sync-version.mjs bump 1.9.1 [buildNumber] # Set explicit version and build number
`);
  process.exit(0);
}
